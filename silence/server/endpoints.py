###############################################################################
# Endpoints: definitions in endpoints/*.json, registry and execution.
#
# Each table has up to two files:
#   endpoints/auto_<table>.json  generated by Silence from the schema (admin
#                                panel). Regenerating it overwrites it.
#   endpoints/<table>.json       custom endpoints. Silence never touches them,
#                                except when the panel moves or saves one.
# An endpoint is identified by its method and route (with any param names):
# the same endpoint cannot be defined twice, in the same or another file.
###############################################################################

ENDPOINTS_DIR = "endpoints"
AUTO_PREFIX = "auto_"
METHODS = ("GET", "POST", "PUT", "DELETE")
EXPECTED_OP = {"GET": "SELECT", "POST": "INSERT", "PUT": "UPDATE", "DELETE": "DELETE"}
KNOWN_KEYS = {"route", "method", "sql", "auth_required", "allowed_roles", "description",
              "request_body_params", "query_params", "owner"}


def endpoints_dir():
    return os.path.join(settings.PROJECT_DIR, ENDPOINTS_DIR)


def table_of_file(filename):
    stem = os.path.splitext(os.path.basename(filename))[0]
    return stem[len(AUTO_PREFIX):] if stem.startswith(AUTO_PREFIX) else stem


def route_key(method, route):
    '''Identity of an endpoint: method and route, ignoring the names of the params'''
    return method.upper() + " " + re.sub(r"\$\w+", "$", "/" + route.strip("/"))


class Endpoint:
    def __init__(self, name, data, filename):
        self.name = name
        self.file = os.path.basename(filename)
        self.table = table_of_file(filename)
        self.source = "auto" if self.file.startswith(AUTO_PREFIX) else "custom"
        self.data = data
        self.warnings = []
        self.overrides = []  # The autogenerated files whose endpoint this one replaces

        unknown = set(data) - KNOWN_KEYS
        if unknown:
            self.warnings.append(f"unknown keys {', '.join(sorted(unknown))}")

        try:
            self.route = "/" + data["route"].strip("/")
            self.sql = data["sql"]
        except KeyError as exc:
            raise EndpointError(f"'{name}' in {self.file} has no {exc.args[0]}")
        self.method = data.get("method", "GET").upper()
        if self.method not in METHODS:
            raise EndpointError(f"'{name}' in {self.file}: unknown method {self.method}")
        self.auth_required = bool(data.get("auth_required", False))
        self.allowed_roles = data.get("allowed_roles", ["*"]) or ["*"]
        self.description = data.get("description", "")
        self.body_params = data.get("request_body_params", []) or []
        # Params of the query string that the SQL uses (?minAverage=7 → $minAverage): filters
        # of a collection, which in REST go in the query string, not in the route
        self.query_params = data.get("query_params", []) or []
        self.owner = data.get("owner") or None

        self.op = sqlshape.sql_op(self.sql)
        self.url_params = sqlshape.params_of(self.route)
        self.sql_params = sqlshape.params_of(self.sql)
        self.uses_logged_id = "loggedId" in self.sql_params
        self.shape = sqlshape.parse(self.sql)
        self.key = route_key(self.method, self.route)
        self.regex = re.compile("^" + re.sub(r"\\\$(\w+)", r"(?P<\1>[^/]+)", re.escape(self.route)) + "$")
        self.literal_segments = sum(1 for s in self.route.split("/") if s and not s.startswith("$"))

        self.check()

    def check(self):
        if self.op in ("SELECT", "DELETE"):
            available = set(self.url_params) | set(self.query_params)
        else:
            available = set(self.url_params) | set(self.query_params) | set(self.body_params)
        if self.owner and isinstance(self.shape, sqlshape.Insert):
            # In a POST with owner, the owner's column comes from the session
            available |= {sqlshape.only_param(v) for c, v in self.shape.pairs if c.lower() == self.owner.lower()}
        missing =[p for p in self.sql_params if p not in available and p != "loggedId"]
        if missing:
            where = "route or query_params" if self.op in ("SELECT", "DELETE") else "route, query_params or request_body_params"
            raise EndpointError(f"'{self.name}' in {self.file}: the SQL uses "
                                f"{', '.join('$' + p for p in missing)}, which is not in the {where}")

        expected = EXPECTED_OP.get(self.method)
        if self.op != "CALL" and expected and self.op != expected:
            self.warnings.append(f"{self.method} usually runs a {expected}, not a {self.op}")

        if self.uses_logged_id and not self.auth_required:
            self.warnings.append("uses $loggedId without auth_required: it may be NULL")

        if self.owner:
            if not settings.AUTH_LINKED:
                raise EndpointError(f"'{self.name}' in {self.file}: owner needs the users table "
                                    "(link it in the admin panel)")
            if self.op == "INSERT" and not isinstance(self.shape, sqlshape.Insert):
                raise EndpointError(f"'{self.name}' in {self.file}: owner needs an INSERT INTO t(...) VALUES (...)")
            if self.op in ("UPDATE", "DELETE") and not (self.shape and self.shape.where):
                raise EndpointError(f"'{self.name}' in {self.file}: owner needs an {self.op} with a WHERE")
            if self.op == "SELECT":
                self.warnings.append("owner has no effect on a GET")

    def to_dict(self):
        return {"name": self.name, "file": self.file, "table": self.table, "source": self.source,
                "route": self.route, "fullRoute": settings.API_PREFIX + self.route,
                "method": self.method, "sql": self.sql, "auth_required": self.auth_required,
                "allowed_roles": self.allowed_roles, "description": self.description,
                "request_body_params": self.body_params, "query_params": self.query_params, "owner": self.owner,
                "overrides": self.overrides, "warnings": self.warnings}


###############################################################################
# Registry
###############################################################################

class Registry:
    def __init__(self):
        self.endpoints = []
        self.errors = []
        self.lock = threading.Lock()

    def load(self):
        '''(Re)loads every endpoints/*.json'''
        endpoints, errors = [], []
        folder = endpoints_dir()
        files = sorted(f for f in os.listdir(folder) if f.endswith(".json")) if os.path.isdir(folder) else []

        for filename in files:
            path = os.path.join(folder, filename)
            if os.path.getsize(path) == 0:
                continue  # Just created by an editor: as if it did not exist yet
            try:
                with open(path, encoding="utf8") as f:
                    content = json.load(f)
                if not isinstance(content, dict):
                    raise EndpointError(f"{filename} must contain an object with one entry per endpoint")
            except (json.JSONDecodeError, EndpointError) as exc:
                errors.append(f"{filename}: {exc}")
                continue

            for name, data in content.items():
                try:
                    endpoints.append(Endpoint(name, data, path))
                except EndpointError as exc:
                    errors.append(str(exc))

        # The same endpoint (method and route) cannot be defined twice
        by_key = {}
        for ep in endpoints:
            by_key.setdefault(ep.key, []).append(ep)
        # The same endpoint (method and route) twice: a custom one prevails over the
        # autogenerated one (which is not generated again); two custom ones are an error
        dropped = set()
        for key, eps in by_key.items():
            if len(eps) < 2:
                continue
            customs = [e for e in eps if e.source == "custom"]
            if len(customs) == 1:
                autos = [e for e in eps if e.source == "auto"]
                customs[0].overrides = [e.file for e in autos]
                dropped.update(id(e) for e in autos)
                logger.debug("%s: %s prevails over %s", key, customs[0].file, ", ".join(e.file for e in autos))
            else:
                where = ", ".join(f"'{e.name}' in {e.file}" for e in customs)
                errors.append(f"{key} is defined more than once ({where}): none of them is loaded. "
                              "Remove all but one.")
                dropped.update(id(e) for e in eps)
        endpoints = [e for e in endpoints if id(e) not in dropped]

        with self.lock:
            self.endpoints = endpoints
            self.errors = errors
        return self

    def log_errors(self):
        for err in self.errors:
            logger.error("Endpoint error: %s", err)

    def match(self, method, path):
        '''Finds the endpoint for a request: (endpoint, url_params) or (None, None).
        Routes with more literal segments win (/employees/logged over /employees/$id)'''
        path = "/" + path.strip("/")
        candidates = []
        for ep in self.endpoints:
            if ep.method != method:
                continue
            m = ep.regex.match(path)
            if m:
                candidates.append((ep.literal_segments, ep, m.groupdict()))
        if not candidates:
            return None, None
        candidates.sort(key=lambda c: -c[0])
        return candidates[0][1], candidates[0][2]

    def route_exists(self, path):
        '''Whether some endpoint matches the path with any method (for 405)'''
        return any(ep.regex.match("/" + path.strip("/")) for ep in self.endpoints)

    def find(self, method, route):
        key = route_key(method, route)
        return next((e for e in self.endpoints if e.key == key), None)


REGISTRY = Registry()


