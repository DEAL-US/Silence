def request_body():
    if request.is_json:
        body = request.get_json(silent=True)
        return body if isinstance(body, dict) else {}
    return request.form.to_dict()


def strip_passwords(rows):
    '''The password column of the users table is never sent to the client'''
    col = settings.USER_AUTH_DATA["password"] if settings.AUTH_LINKED else None
    if not col:
        return rows
    for row in rows:
        for key in [k for k in row if k.lower() == col.lower()]:
            del row[key]
    return rows


def filter_query_results(data, args):
    '''Filtering, sorting and paging with the query string, as in Silence 2:
    ?column=value, _sort, _order=asc|desc, _limit and _page'''
    sort_param = args.get("_sort")
    sort_reverse = args.get("_order") == "desc"

    try:
        limit = int(args.get("_limit", None))
    except (ValueError, TypeError):
        limit = None

    try:
        page = int(args.get("_page", None))
    except (ValueError, TypeError):
        page = None

    filter_criteria = [pair for pair in args.items() if not pair[0].startswith("_")]
    filter_func = lambda elem: all(k not in elem or str(elem[k]).lower() == v.lower() for k, v in filter_criteria)
    res = list(filter(filter_func, data))

    if sort_param:
        def order_key_func(elem):
            v = elem.get(sort_param)
            return v if v is not None else Min
        try:
            res.sort(key=order_key_func, reverse=sort_reverse)
        except TypeError:
            pass

    offset = limit * page if limit and page else 0
    top = offset + limit if limit else len(res)
    return res[offset:top]


def is_auth_table(table):
    return settings.AUTH_LINKED and table.lower() == settings.USER_AUTH_DATA["table"].lower()


def column_is_optional(table, column):
    rel = get_schema().get(table)
    col = rel.column(column) if rel else None
    return col is not None and col.optional


def run(ep, url_params):
    '''Runs an endpoint for the current request. Returns (result, status)'''
    user = get_logged_user(required=ep.auth_required or bool(ep.owner))
    if ep.auth_required or ep.owner:
        check_roles(user, ep.allowed_roles)

    params = dict(url_params)
    if ep.uses_logged_id:
        params["loggedId"] = user_id_of(user)
    for p in ep.query_params:
        if p not in request.args:
            raise HTTPError(400, f"Missing parameter '{p}' in the query string (?{p}=...)")
        params[p] = request.args[p]

    try:
        if ep.op == "SELECT":
            rows = dal.query(sqlshape.to_pyformat(ep.sql), params)
            # The query string also filters and sorts (not with the params that the SQL uses)
            args = {k: v for k, v in request.args.items() if k not in ep.query_params}
            rows = filter_query_results(strip_passwords(rows), args)
            # In our teaching context, if the route ends with a param and there
            # are no results, the resource does not exist
            if ep.route.rstrip("/").split("/")[-1].startswith("$") and not rows:
                raise HTTPError(404, "Not found")
            return rows, 200

        body = request_body()
        values = {p: body[p] for p in ep.body_params if p in body}
        sql = prepare_statement(ep, params, values, user)
        res = dal.update(sqlshape.to_pyformat(sql), {**values, **params})
        if "rows" in res:
            res["rows"] = strip_passwords(res["rows"])

        if ep.op == "INSERT":
            return res, 201
        if ep.op in ("UPDATE", "DELETE") and res["affectedRows"] == 0 and ep.url_params:
            raise HTTPError(404, "Not found")
        return res, 200
    except DatabaseError as exc:
        raise to_http_error(exc, f"endpoint '{ep.name}' ({ep.file})")


def prepare_statement(ep, params, values, user):
    '''Applies the rules of Silence 3 to a POST/PUT/DELETE and returns its SQL:
    owner, optional columns, partial updates and password hashing'''
    shape = ep.shape
    pairs = list(shape.pairs) if isinstance(shape, (sqlshape.Insert, sqlshape.Update)) else None

    # Owner: in a POST the owner is the logged user, whatever the body says
    if ep.owner and ep.op == "INSERT":
        uid = user_id_of(user)
        owner_param = next((sqlshape.only_param(v) for c, v in pairs if c.lower() == ep.owner.lower()), None)
        if owner_param:
            values[owner_param] = uid
        else:
            pairs.append((ep.owner, "$__owner"))
            values["__owner"] = uid

    # Params that the request did not send
    missing = [p for p in ep.sql_params if p not in params and p not in values and p != "loggedId"]
    if missing and pairs is not None:
        kept = []
        for col, expr in pairs:
            p = sqlshape.only_param(expr)
            if p in missing:
                if ep.op == "UPDATE":
                    continue  # PUT: the columns that are not sent keep their value
                if column_is_optional(shape.table, col):
                    continue  # POST: the DB uses the column's default (or NULL)
                raise HTTPError(400, f"Missing parameter '{p}' in the request body")
            kept.append((col, expr))
        pairs = kept
        if not pairs:
            raise HTTPError(400, "The request body has none of the parameters " +
                            ", ".join(f"'{p}'" for p in ep.body_params))
    elif missing:
        raise HTTPError(400, f"Missing parameter '{missing[0]}' in the request body")

    if isinstance(shape, sqlshape.Insert):
        sql = sqlshape.Insert(shape.table, pairs).sql()
    elif isinstance(shape, sqlshape.Update):
        sql = sqlshape.Update(shape.table, pairs, shape.where).sql()
    else:
        sql = ep.sql

    # A param that is still used (e.g., inside an expression) must be sent
    still_missing = [p for p in sqlshape.params_of(sql)
                     if p not in params and p not in values and p != "loggedId"]
    if still_missing:
        raise HTTPError(400, f"Missing parameter '{still_missing[0]}' in the request body")

    # Passwords of the users table are stored hashed (in argon2 mode)
    if pairs is not None and is_auth_table(shape.table):
        pwd_col = settings.USER_AUTH_DATA["password"].lower()
        for col, expr in pairs:
            p = sqlshape.only_param(expr)
            if col.lower() == pwd_col and p in values:
                values[p] = prepare_for_storage(values[p])

    # Owner: a PUT or DELETE only acts on the rows of the logged user
    if ep.owner and ep.op in ("UPDATE", "DELETE"):
        check_owner(ep, {**values, **params}, user)

    return sql


def check_owner(ep, all_params, user):
    shape = ep.shape
    q = f"SELECT {ep.owner} AS owner FROM {shape.table} WHERE {shape.where}"
    rows = dal.query(sqlshape.to_pyformat(q), all_params)
    if not rows:
        raise HTTPError(404, "Not found")
    uid = user_id_of(user)
    if any(str(r["owner"]) != str(uid) for r in rows):
        raise HTTPError(403, "Only the owner can modify or delete this resource")
