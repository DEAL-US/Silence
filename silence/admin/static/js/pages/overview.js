// Overview: the steps to get the project working, and the current problems.
import { esc } from "../ui.js";

export async function render(main, app) {
  const s = app.status;
  if (!s) {
    main.innerHTML = `<h1>Silence</h1><div class="ez-alert ez-alert--error">Cannot reach Silence.</div>`;
    return;
  }
  const dbOk = !s.database.error;
  const step = (done, title, text, href, action) => `
    <li class="${done ? "sa-done" : ""}">
      <div><strong>${title}</strong><br><span class="sa-muted">${text}</span></div>
      <a class="ez-button ${done ? "ez-button--secondary" : ""}" href="${href}">${action}</a>
    </li>`;

  const errors = [...s.endpoints.errors, ...s.tests.errors];
  main.innerHTML = `
    <h1>${esc(s.project)}</h1>
    <p class="sa-muted sa-small">${esc(s.projectDir)}</p>
    ${errors.length ? `<div class="ez-alert ez-alert--error"><strong>Problems in the project files</strong>
      <ul>${errors.map((e) => `<li>${esc(e)}</li>`).join("")}</ul></div>` : ""}
    <ol class="sa-steps">
      ${step(dbOk, "Connect to the database",
        dbOk ? `Connected to <code>${esc(s.database.name)}</code>.` : esc(s.database.error),
        "#/database", dbOk ? "Change" : "Set up")}
      ${step(s.auth.linked, "Link the users table (optional)",
        s.auth.linked ? `Users in <code>${esc(s.auth.table)}</code>, identified by <code>${esc(s.auth.identifier)}</code>; passwords: ${esc(s.auth.password_mode)}.`
          : "Needed for login, register, sessions, roles and owners.",
        "#/database", s.auth.linked ? "Change" : "Link")}
      ${step(s.endpoints.count > 0, "Generate the endpoints",
        s.endpoints.count ? `${s.endpoints.count} endpoints: ${s.endpoints.auto} autogenerated, ${s.endpoints.custom} custom.`
          : "One file per table in endpoints/, from the database schema.",
        "#/endpoints", s.endpoints.count ? "Manage" : "Generate")}
      ${step(s.tests.count > 0, "Generate and run the tests",
        s.tests.count ? `${s.tests.count} tests in tests/.` : "Positive and negative tests from the endpoints.",
        "#/tests", s.tests.count ? "Run" : "Generate")}
    </ol>
    <section class="sa-section">
      <h2>Your app</h2>
      <p>The web app is served from <code>web/</code> at <a href="/" target="_blank">${esc(s.baseUrl)}/</a>,
        and the API at <a href="${esc(s.apiPrefix)}" target="_blank">${esc(s.baseUrl + s.apiPrefix)}</a>.
        The requests to both are shown in the console where <code>silence run</code> is running.</p>
    </section>`;
}
